/**
 * Writes worker/routes.ts from the tool folders.
 *
 * The worker has to know which paths are real in order to 404 the ones that are not,
 * but it cannot import the registry — that pulls in Vue components. A second list
 * maintained by hand would drift the first time someone adds a tool, so it is generated
 * here and regenerated on every build (see the `prebuild` script).
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const toolsDir = join(root, 'src', 'tools')
const outFile = join(root, 'worker', 'routes.ts')

const slugs = readdirSync(toolsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => {
    const source = readFileSync(join(toolsDir, entry.name, 'index.ts'), 'utf8')
    const match = source.match(/slug:\s*'([^']+)'/)
    if (!match) throw new Error(`src/tools/${entry.name}/index.ts declares no slug`)
    return match[1]
  })
  .sort()

const duplicates = slugs.filter((slug, i) => slugs.indexOf(slug) !== i)
if (duplicates.length) throw new Error(`duplicate slugs: ${duplicates.join(', ')}`)

// A slug that collides with something resolved ahead of the SPA would be unreachable.
const RESERVED = new Set(['api', 'assets', 'index.html'])
const clashes = slugs.filter((slug) => RESERVED.has(slug))
if (clashes.length) throw new Error(`slugs collide with reserved paths: ${clashes.join(', ')}`)

const body = `// Generated by scripts/generate-worker-routes.mjs — do not edit by hand.
// Regenerated on every build; run \`npm run build\` after adding or renaming a tool.

export const TOOL_ROUTES: ReadonlySet<string> = new Set([
${slugs.map((slug) => `  '${slug}',`).join('\n')}
])
`

writeFileSync(outFile, body)
console.log(`worker/routes.ts: ${slugs.length} routes`)

/**
 * The social image carries the tool count as baked-in pixels, so it cannot recompute
 * itself the way the home page does — and it has already gone stale twice. Warn rather
 * than fail: re-rendering needs a headless browser, and a missing browser should not
 * stop a deploy over a picture.
 */
const ogFile = join(root, 'design', 'og-image.html')
const og = readFileSync(ogFile, 'utf8')
const shown = og.match(/Tools (\d+) · Deps (\d+)/)
const realDeps = Object.keys(JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).dependencies ?? {}).length

if (!shown) {
  console.warn('warning: design/og-image.html has no "Tools N · Deps N" line to check')
} else if (Number(shown[1]) !== slugs.length || Number(shown[2]) !== realDeps) {
  console.warn(
    `warning: design/og-image.html says Tools ${shown[1]} · Deps ${shown[2]}, ` +
      `but there are ${slugs.length} tools and ${realDeps} dependencies. ` +
      'Update it and re-render public/og-social.png.',
  )
}
